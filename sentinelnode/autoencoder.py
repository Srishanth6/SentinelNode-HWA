"""Tiny dense autoencoder for on-device health scoring, with int8 weight export for the ESP32.

Pipeline (all data SIMULATED until the hardware build is done):
  1. standardise the 6 features with mean/std of healthy data
  2. train a 6-8-3-8-6 ReLU autoencoder (scikit-learn MLPRegressor, X -> X)
  3. threshold = 99.5th percentile of reconstruction error on held-out healthy data
  4. quantise every weight matrix to int8 (symmetric, one scale per layer); activations stay float32
  5. write firmware/sentinelnode/ae_model.h so the ESP32 runs the same maths in plain C

Weights are int8, so the model is about 0.2 kB on the node and needs no TFLite runtime.
A full-integer TensorFlow Lite Micro build is listed as the next step in docs/FEATURES_AND_LIMITATIONS.md.
"""
from __future__ import annotations
import json
from dataclasses import dataclass, field
from pathlib import Path
import numpy as np
from sklearn.neural_network import MLPRegressor
from . import FEATURES

HIDDEN = (8, 3, 8)


@dataclass
class QuantAE:
    mean: np.ndarray
    std: np.ndarray
    w_q: list            # int8 weight matrices
    w_scale: list        # float scale per layer
    biases: list         # float32 biases
    threshold: float     # reconstruction-MSE threshold (healthy 99.5th pct)
    meta: dict = field(default_factory=dict)

    def _forward(self, z: np.ndarray) -> np.ndarray:
        a = z
        n = len(self.w_q)
        for k in range(n):
            a = a @ (self.w_q[k].astype(np.float32) * self.w_scale[k]) + self.biases[k]
            if k < n - 1:
                a = np.maximum(a, 0.0)
        return a

    def error(self, X: np.ndarray) -> np.ndarray:
        z = (np.atleast_2d(X) - self.mean) / self.std
        return np.mean((self._forward(z) - z) ** 2, axis=1)

    def health(self, X: np.ndarray) -> np.ndarray:
        """0-100; 50 at the threshold, 0 at 3x the threshold or worse."""
        e = self.error(X)
        h = np.where(e <= self.threshold,
                     100 - 50 * e / self.threshold,
                     50 - 25 * (e - self.threshold) / self.threshold)
        return np.clip(np.round(h), 0, 100)


def to_matrix(rows) -> np.ndarray:
    return np.array([[r[f] for f in FEATURES] for r in rows], dtype=np.float32)


def _quant(w: np.ndarray):
    scale = float(np.max(np.abs(w)) / 127.0) or 1.0
    return np.clip(np.round(w / scale), -127, 127).astype(np.int8), np.float32(scale)


def train(healthy_rows, seed: int = 0, pct: float = 99.5) -> QuantAE:
    X = to_matrix(healthy_rows)
    rng = np.random.default_rng(seed)
    idx = rng.permutation(len(X))
    cut = int(0.8 * len(X))
    tr, va = X[idx[:cut]], X[idx[cut:]]
    mean, std = tr.mean(0), tr.std(0) + 1e-6
    ztr = (tr - mean) / std
    mlp = MLPRegressor(hidden_layer_sizes=HIDDEN, activation="relu", max_iter=3000,
                       learning_rate_init=3e-3, alpha=1e-4, random_state=seed)
    mlp.fit(ztr, ztr)
    wq, ws = zip(*[_quant(w) for w in mlp.coefs_])
    ae = QuantAE(mean.astype(np.float32), std.astype(np.float32), list(wq), list(ws),
                 [b.astype(np.float32) for b in mlp.intercepts_], 1.0)
    ae.threshold = float(np.percentile(ae.error(va), pct))
    ae.meta = {"hidden": list(HIDDEN), "n_train": int(len(tr)), "n_val": int(len(va)),
               "threshold_pct": pct, "data": "SIMULATED healthy readings (sim/simulator.py)",
               "weight_bytes": int(sum(w.size for w in wq))}
    return ae


def export_header(ae: QuantAE, path: str | Path) -> Path:
    """Write a C header the ESP32 firmware #includes (see ae_infer() in sentinelnode.ino)."""
    def arr(name, a, ctype):
        flat = ", ".join(str(int(x)) if ctype == "int8_t" else f"{float(x):.8g}f" for x in np.ravel(a))
        return f"static const {ctype} {name}[{np.size(a)}] = {{{flat}}};\n"
    dims = [ae.w_q[0].shape[0]] + [w.shape[1] for w in ae.w_q]
    s = ["// AUTO-GENERATED by sentinelnode/autoencoder.py -- do not edit by hand.\n",
         "// Trained on SIMULATED healthy data; retrain on the real board's healthy baseline.\n",
         "#pragma once\n#include <stdint.h>\n",
         f"#define AE_N_LAYERS {len(ae.w_q)}\n#define AE_N_IN {dims[0]}\n#define AE_MAX_W {max(dims)}\n",
         f"static const int AE_DIMS[{len(dims)}] = {{{', '.join(map(str, dims))}}};\n",
         f"static const float AE_THRESHOLD = {ae.threshold:.8g}f;\n",
         arr("AE_MEAN", ae.mean, "float"), arr("AE_STD", ae.std, "float")]
    for k, (w, sc, b) in enumerate(zip(ae.w_q, ae.w_scale, ae.biases)):
        s.append(f"static const float AE_S{k} = {float(sc):.8g}f;\n")
        s.append(arr(f"AE_W{k}", w, "int8_t"))   # row-major [in][out]
        s.append(arr(f"AE_B{k}", b, "float"))
    s.append("static const int8_t* const AE_W[AE_N_LAYERS] = {" + ", ".join(f"AE_W{k}" for k in range(len(ae.w_q))) + "};\n")
    s.append("static const float AE_S[AE_N_LAYERS] = {" + ", ".join(f"AE_S{k}" for k in range(len(ae.w_q))) + "};\n")
    s.append("static const float* const AE_B[AE_N_LAYERS] = {" + ", ".join(f"AE_B{k}" for k in range(len(ae.w_q))) + "};\n")
    p = Path(path); p.write_text("".join(s)); return p


def save_json(ae: QuantAE, path: str | Path):
    Path(path).write_text(json.dumps({
        "mean": ae.mean.tolist(), "std": ae.std.tolist(), "threshold": ae.threshold,
        "w_q": [w.tolist() for w in ae.w_q], "w_scale": [float(s) for s in ae.w_scale],
        "biases": [b.tolist() for b in ae.biases], "meta": ae.meta}, indent=1))


def load_json(path: str | Path) -> QuantAE:
    d = json.loads(Path(path).read_text())
    return QuantAE(np.array(d["mean"], np.float32), np.array(d["std"], np.float32),
                   [np.array(w, np.int8) for w in d["w_q"]], [np.float32(s) for s in d["w_scale"]],
                   [np.array(b, np.float32) for b in d["biases"]], d["threshold"], d["meta"])


if __name__ == "__main__":
    from sim.simulator import dataset
    ae = train(dataset(3000, seed=0))
    save_json(ae, "models/ae_int8.json")
    print("header ->", export_header(ae, "firmware/sentinelnode/ae_model.h"))
    print("threshold", round(ae.threshold, 4), ae.meta)
